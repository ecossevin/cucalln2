MODULE CUADJTQ_LOKI_MOD
  CONTAINS
  SUBROUTINE CUADJTQ_LOKI (YDTHF, YDCST, YDEPHLI, KIDIA, KFDIA, KLON, KLEV, KK, PSP, PT, PQ, LDFLAG, KCALL, LDOFLAG, YDSTACK_L)
    
    !          PURPOSE.
    !          --------
    !          TO PRODUCE T,Q AND L VALUES FOR CLOUD ASCENT
    
    !          INTERFACE
    !          ---------
    !          THIS ROUTINE IS CALLED FROM SUBROUTINES:
    !              *COND*     (T AND Q AT CONDENSATION LEVEL)
    !              *CUBASE*   (T AND Q AT CONDENSATION LEVEL)
    !              *CUASC*    (T AND Q AT CLOUD LEVELS)
    !              *CUINI*    (ENVIRONMENTAL T AND QS VALUES AT HALF LEVELS)
    !              *CUSTRAT*  (T AND Q AT CONDENSATION LEVEL)
    !          INPUT ARE UNADJUSTED T AND Q VALUES,
    !          IT RETURNS ADJUSTED VALUES OF T AND Q
    
    !     PARAMETER     DESCRIPTION                                   UNITS
    !     ---------     -----------                                   -----
    !     INPUT PARAMETERS (INTEGER):
    
    !    *KIDIA*        START POINT
    !    *KFDIA*        END POINT
    !    *KLON*         NUMBER OF GRID POINTS PER PACKET
    !    *KLEV*         NUMBER OF LEVELS
    !    *KK*           LEVEL
    !    *KCALL*        DEFINES CALCULATION AS
    !                      KCALL=0  ENV. T AND QS IN*CUINI*
    !                      KCALL=1  CONDENSATION IN UPDRAFTS  (E.G. CUBASE, CUASC)
    !                      KCALL=2  EVAPORATION IN DOWNDRAFTS (E.G. CUDLFS,CUDDRAF)
    
    !     INPUT PARAMETERS (LOGICAL):
    
    !    *LDLAND*       LAND-SEA MASK (.TRUE. FOR LAND POINTS)
    
    !     INPUT PARAMETERS (REAL):
    
    !    *PSP*          PRESSURE                                        PA
    
    !     UPDATED PARAMETERS (REAL):
    
    !    *PT*           TEMPERATURE                                     K
    !    *PQ*           SPECIFIC HUMIDITY                             KG/KG
    
    !          EXTERNALS
    !          ---------
    !          3 LOOKUP TABLES ( TLUCUA, TLUCUB, TLUCUC )
    !          FOR CONDENSATION CALCULATIONS.
    !          THE TABLES ARE INITIALISED IN *SUPHEC*.
    
    !     AUTHOR.
    !     -------
    !      M.TIEDTKE         E.C.M.W.F.     12/89
    
    !     MODIFICATIONS.
    !     --------------
    !      J.HAGUE               03-01-13   MASS Vector Functions
    !      J.HAGUE               03-07-07   More MASS V.F.
    !      M.Hamrud              01-Oct-2003 CY28 Cleaning
    !      J.Hague & D.Salmond   22-Nov-2005 Optimisations
    !     R. El Khatib 22-Jun-2022 A contribution to simplify phasing after the refactoring of YOMCLI/YOMCST/YOETHF.
    !----------------------------------------------------------------------
    
    USE, intrinsic :: ISO_FORTRAN_ENV, ONLY: REAL64
    USE, intrinsic :: ISO_C_BINDING, ONLY: C_SIZEOF
    USE PARKIND1, ONLY: JPIM, JPRB
    USE YOMHOOK, ONLY: LHOOK, JPHOOK
    
    USE YOMCST, ONLY: TCST
    USE YOETHF, ONLY: TTHF
    USE YOEPHLI, ONLY: TEPHLI
    
    IMPLICIT NONE
    
    TYPE(TTHF), INTENT(IN) :: YDTHF
    TYPE(TCST), INTENT(IN) :: YDCST
    TYPE(TEPHLI), INTENT(IN) :: YDEPHLI
    INTEGER(KIND=JPIM), INTENT(IN) :: KIDIA
    INTEGER(KIND=JPIM), INTENT(IN) :: KFDIA
    INTEGER(KIND=JPIM), INTENT(IN) :: KLON
    INTEGER(KIND=JPIM), INTENT(IN) :: KLEV
    INTEGER(KIND=JPIM), INTENT(IN) :: KK
    REAL(KIND=JPRB), INTENT(IN) :: PSP(KLON)
    REAL(KIND=JPRB), INTENT(INOUT) :: PT(KLON, KLEV)
    REAL(KIND=JPRB), INTENT(INOUT) :: PQ(KLON, KLEV)
    LOGICAL, INTENT(IN) :: LDFLAG(KLON)
    INTEGER(KIND=JPIM), INTENT(IN) :: KCALL
    LOGICAL, OPTIONAL, INTENT(IN) :: LDOFLAG(KLON)
    
    INTEGER(KIND=JPIM) :: JL
    
    REAL(KIND=JPRB) :: Z1S, CUADJTQ_Z2S, CUADJTQ_ZCOND, CUADJTQ_ZCOND1, CUADJTQ_ZCOR, ZFOEEWI, ZFOEEWL, CUADJTQ_ZOEALFA,  &
    & CUADJTQ_ZQMAX, CUADJTQ_ZQSAT, CUADJTQ_ZTARG, CUADJTQ_ZQP
    REAL(KIND=JPRB) :: ZL, ZI, ZF
    
    LOGICAL :: CUADJTQ_LLFLAG
    
#include "abor1.intfb.h"
    
    !DIR$ VFUNCTION EXPHF
#include "fcttre.func.h"
#include "cuadjtq.func.h"
    
    !     STATEMENT FUNCTIONS
    
    REAL(KIND=JPHOOK) :: CUADJTQ_ZHOOK_HANDLE
!$acc routine vector
    INTEGER(KIND=8) :: YLSTACK_L
    INTEGER(KIND=8), INTENT(INOUT) :: YDSTACK_L
    YLSTACK_L = YDSTACK_L
!$acc data present( PSP, PT, PQ, LDFLAG, LDOFLAG, YDTHF, YDCST, YDEPHLI )
    
    !----------------------------------------------------------------------
    
    !     1.           DEFINE CONSTANTS
    !                  ----------------
    
    
    !IF (LHOOK) CALL DR_HOOK('CUADJTQ',0,ZHOOK_HANDLE)
    
    
    CUADJTQ_ZQMAX = 0.5_JPRB
    
    !*********************************************
    
!$acc loop vector
    DO JL=KIDIA,KFDIA
      IF (.not.YDEPHLI%LPHYLIN) THEN
        !*********************************************
        
        !     2.           CALCULATE CONDENSATION AND ADJUST T AND Q ACCORDINGLY
        !                  -----------------------------------------------------
        
        IF (KCALL == 1 .or. KCALL == 6) THEN
          
          !   mixed phase saturation
          
          CUADJTQ_LLFLAG = LDFLAG(JL)
          IF (KCALL == 6) THEN
            IF (PRESENT(LDOFLAG)) THEN
              CUADJTQ_LLFLAG = CUADJTQ_LLFLAG .and. .not.LDOFLAG(JL)
            END IF
          END IF
          
          IF (CUADJTQ_LLFLAG) THEN
            CUADJTQ_ZQP = 1.0_JPRB / PSP(JL)
            ZL = 1.0_JPRB / (PT(JL, KK) - YDTHF%R4LES)
            ZI = 1.0_JPRB / (PT(JL, KK) - YDTHF%R4IES)
            !       ZQSAT=FOEEWMCU(PT(JL,KK))*ZQP
            CUADJTQ_ZQSAT = YDTHF%R2ES*(FOEALFCU(PT(JL, KK))*EXP(YDTHF%R3LES*(PT(JL, KK) - YDCST%RTT)*ZL) + (1.0_JPRB -  &
            & FOEALFCU(PT(JL, KK)))*EXP(YDTHF%R3IES*(PT(JL, KK) - YDCST%RTT)*ZI))
            CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZQP
            CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
            CUADJTQ_ZCOR = 1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT
            ZF = FOEALFCU(PT(JL, KK))*YDTHF%R5ALVCP*ZL**2 + (1.0_JPRB - FOEALFCU(PT(JL, KK)))*YDTHF%R5ALSCP*ZI**2
            CUADJTQ_ZCOND = (PQ(JL, KK)*CUADJTQ_ZCOR**2 - CUADJTQ_ZQSAT*CUADJTQ_ZCOR) / (CUADJTQ_ZCOR**2 + CUADJTQ_ZQSAT*ZF)
            CUADJTQ_ZCOND = MAX(CUADJTQ_ZCOND, 0.0_JPRB)
            PT(JL, KK) = PT(JL, KK) + FOELDCPMCU(PT(JL, KK))*CUADJTQ_ZCOND
            PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND
            ZL = 1.0_JPRB / (PT(JL, KK) - YDTHF%R4LES)
            ZI = 1.0_JPRB / (PT(JL, KK) - YDTHF%R4IES)
            !       ZQSAT=FOEEWMCU(PT(JL,KK))*ZQP
            CUADJTQ_ZQSAT = YDTHF%R2ES*(FOEALFCU(PT(JL, KK))*EXP(YDTHF%R3LES*(PT(JL, KK) - YDCST%RTT)*ZL) + (1.0_JPRB -  &
            & FOEALFCU(PT(JL, KK)))*EXP(YDTHF%R3IES*(PT(JL, KK) - YDCST%RTT)*ZI))
            CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZQP
            CUADJTQ_ZQSAT = FMINJ(0.5_JPRB, CUADJTQ_ZQSAT)
            CUADJTQ_ZCOR = 1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT
            ZF = FOEALFCU(PT(JL, KK))*YDTHF%R5ALVCP*ZL**2 + (1.0_JPRB - FOEALFCU(PT(JL, KK)))*YDTHF%R5ALSCP*ZI**2
            CUADJTQ_ZCOND1 = (PQ(JL, KK)*CUADJTQ_ZCOR**2 - CUADJTQ_ZQSAT*CUADJTQ_ZCOR) / (CUADJTQ_ZCOR**2 + CUADJTQ_ZQSAT*ZF)
            IF (CUADJTQ_ZCOND == 0.0_JPRB) CUADJTQ_ZCOND1 = 0.0_JPRB
            PT(JL, KK) = PT(JL, KK) + FOELDCPMCU(PT(JL, KK))*CUADJTQ_ZCOND1
            PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND1
          END IF
          
          IF (KCALL == 6) THEN
            
            IF (LDFLAG(JL) .and. LDOFLAG(JL)) THEN
              CUADJTQ_ZQP = 1.0_JPRB / PSP(JL)
              ZL = 1.0_JPRB / (PT(JL, KK) - YDTHF%R4LES)
              CUADJTQ_ZQSAT = YDTHF%R2ES*EXP(YDTHF%R3LES*(PT(JL, KK) - YDCST%RTT)*ZL)
              CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZQP
              CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
              CUADJTQ_ZCOR = 1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT
              ZF = YDTHF%R5ALVCP*ZL**2
              CUADJTQ_ZCOND = (PQ(JL, KK)*CUADJTQ_ZCOR**2 - CUADJTQ_ZQSAT*CUADJTQ_ZCOR) / (CUADJTQ_ZCOR**2 + CUADJTQ_ZQSAT*ZF)
              CUADJTQ_ZCOND = MAX(CUADJTQ_ZCOND, 0.0_JPRB)
              PT(JL, KK) = PT(JL, KK) + YDTHF%RALVDCP*CUADJTQ_ZCOND
              PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND
              ZL = 1.0_JPRB / (PT(JL, KK) - YDTHF%R4LES)
              CUADJTQ_ZQSAT = YDTHF%R2ES*EXP(YDTHF%R3LES*(PT(JL, KK) - YDCST%RTT)*ZL)
              CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZQP
              CUADJTQ_ZQSAT = FMINJ(0.5_JPRB, CUADJTQ_ZQSAT)
              CUADJTQ_ZCOR = 1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT
              ZF = YDTHF%R5ALVCP*ZL**2
              CUADJTQ_ZCOND1 = (PQ(JL, KK)*CUADJTQ_ZCOR**2 - CUADJTQ_ZQSAT*CUADJTQ_ZCOR) / (CUADJTQ_ZCOR**2 + CUADJTQ_ZQSAT*ZF)
              IF (CUADJTQ_ZCOND == 0.0_JPRB) CUADJTQ_ZCOND1 = 0.0_JPRB
              PT(JL, KK) = PT(JL, KK) + YDTHF%RALVDCP*CUADJTQ_ZCOND1
              PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND1
            END IF
            
          END IF
          
        END IF
        
        IF (KCALL == 2) THEN
          
          !DIR$    IVDEP
          !OCL NOVREC
          IF (LDFLAG(JL)) THEN
            CUADJTQ_ZQP = 1.0_JPRB / PSP(JL)
            CUADJTQ_ZQSAT = FOEEWMCU(PT(JL, KK))*CUADJTQ_ZQP
            CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
            CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
            CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
            CUADJTQ_ZCOND = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEMCU(PT(JL, KK)))
            CUADJTQ_ZCOND = MIN(CUADJTQ_ZCOND, 0.0_JPRB)
            PT(JL, KK) = PT(JL, KK) + FOELDCPMCU(PT(JL, KK))*CUADJTQ_ZCOND
            PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND
            CUADJTQ_ZQSAT = FOEEWMCU(PT(JL, KK))*CUADJTQ_ZQP
            CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
            CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
            CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
            CUADJTQ_ZCOND1 = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEMCU(PT(JL, KK)))
            IF (CUADJTQ_ZCOND == 0.0_JPRB) CUADJTQ_ZCOND1 = MIN(CUADJTQ_ZCOND1, 0.0_JPRB)
            PT(JL, KK) = PT(JL, KK) + FOELDCPMCU(PT(JL, KK))*CUADJTQ_ZCOND1
            PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND1
          END IF
          
        END IF
        
        IF (KCALL == 0) THEN
          
          !DIR$    IVDEP
          !OCL NOVREC
          
          !DIR$ LOOP_INFO EST_TRIPS(16)
          CUADJTQ_ZQP = 1.0_JPRB / PSP(JL)
          CUADJTQ_ZQSAT = FOEEWM(PT(JL, KK))*CUADJTQ_ZQP
          CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
          CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
          CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
          CUADJTQ_ZCOND1 = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEM(PT(JL, KK)))
          PT(JL, KK) = PT(JL, KK) + FOELDCPM(PT(JL, KK))*CUADJTQ_ZCOND1
          PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND1
          CUADJTQ_ZQSAT = FOEEWM(PT(JL, KK))*CUADJTQ_ZQP
          CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
          CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
          CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
          CUADJTQ_ZCOND1 = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEM(PT(JL, KK)))
          PT(JL, KK) = PT(JL, KK) + FOELDCPM(PT(JL, KK))*CUADJTQ_ZCOND1
          PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND1
          
        END IF
        
        IF (KCALL == 4) THEN
          
          IF (LDFLAG(JL)) THEN
            CUADJTQ_ZQP = 1.0_JPRB / PSP(JL)
            CUADJTQ_ZQSAT = FOEEWM(PT(JL, KK))*CUADJTQ_ZQP
            CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
            CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
            CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
            CUADJTQ_ZCOND = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEM(PT(JL, KK)))
            PT(JL, KK) = PT(JL, KK) + FOELDCPM(PT(JL, KK))*CUADJTQ_ZCOND
            PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND
            CUADJTQ_ZQSAT = FOEEWM(PT(JL, KK))*CUADJTQ_ZQP
            CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
            CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
            CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
            CUADJTQ_ZCOND1 = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEM(PT(JL, KK)))
            PT(JL, KK) = PT(JL, KK) + FOELDCPM(PT(JL, KK))*CUADJTQ_ZCOND1
            PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND1
          END IF
          
        END IF
        
        IF (KCALL == 5) THEN
          ! Same as 4 but with LDFLAG all true
          
          !OCL NOVREC
          !DIR$    IVDEP
          !DIR$ LOOP_INFO EST_TRIPS(16)
          CUADJTQ_ZQP = 1.0_JPRB / PSP(JL)
          CUADJTQ_ZQSAT = FOEEWM(PT(JL, KK))*CUADJTQ_ZQP
          CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
          CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
          CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
          CUADJTQ_ZCOND = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEM(PT(JL, KK)))
          PT(JL, KK) = PT(JL, KK) + FOELDCPM(PT(JL, KK))*CUADJTQ_ZCOND
          PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND
          CUADJTQ_ZQSAT = FOEEWM(PT(JL, KK))*CUADJTQ_ZQP
          CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
          CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
          CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
          CUADJTQ_ZCOND1 = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEM(PT(JL, KK)))
          PT(JL, KK) = PT(JL, KK) + FOELDCPM(PT(JL, KK))*CUADJTQ_ZCOND1
          PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND1
        END IF
        
        IF (KCALL == 3) THEN
          !DIR$ LOOP_INFO EST_TRIPS(16)
          CUADJTQ_ZQP = 1.0_JPRB / PSP(JL)
          CUADJTQ_ZQSAT = FOEEWMCU(PT(JL, KK))*CUADJTQ_ZQP
          CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
          CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
          CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
          CUADJTQ_ZCOND1 = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEMCU(PT(JL, KK)))
          PT(JL, KK) = PT(JL, KK) + FOELDCPMCU(PT(JL, KK))*CUADJTQ_ZCOND1
          PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND1
          CUADJTQ_ZQSAT = FOEEWMCU(PT(JL, KK))*CUADJTQ_ZQP
          CUADJTQ_ZQSAT = MIN(0.5_JPRB, CUADJTQ_ZQSAT)
          CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
          CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
          CUADJTQ_ZCOND1 = (PQ(JL, KK) - CUADJTQ_ZQSAT) / (1.0_JPRB + CUADJTQ_ZQSAT*CUADJTQ_ZCOR*FOEDEMCU(PT(JL, KK)))
          PT(JL, KK) = PT(JL, KK) + FOELDCPMCU(PT(JL, KK))*CUADJTQ_ZCOND1
          PQ(JL, KK) = PQ(JL, KK) - CUADJTQ_ZCOND1
          
        END IF
        !*********************************************
      ELSE
        !*********************************************
        
        !     2.           CALCULATE CONDENSATION AND ADJUST T AND Q ACCORDINGLY
        !                  -----------------------------------------------------
        
        IF (KCALL == 1) THEN
          
          !DIR$    IVDEP
          !OCL NOVREC
          !DIR$ LOOP_INFO EST_TRIPS(16)
          IF (LDFLAG(JL)) THEN
            CUADJTQ_ZQP = 1.0_JPRB / PSP(JL)
            CUADJTQ_ZTARG = PT(JL, KK)
            CUADJTQ_ZOEALFA = 0.5_JPRB*(TANH(YDEPHLI%RLPAL1*(CUADJTQ_ZTARG - YDEPHLI%RLPTRC)) + 1.0_JPRB)
            ZFOEEWL = YDTHF%R2ES*EXP(YDTHF%R3LES*(CUADJTQ_ZTARG - YDCST%RTT) / (CUADJTQ_ZTARG - YDTHF%R4LES))
            ZFOEEWI = YDTHF%R2ES*EXP(YDTHF%R3IES*(CUADJTQ_ZTARG - YDCST%RTT) / (CUADJTQ_ZTARG - YDTHF%R4IES))
            CUADJTQ_ZQSAT = CUADJTQ_ZQP*(CUADJTQ_ZOEALFA*ZFOEEWL + (1.0_JPRB - CUADJTQ_ZOEALFA)*ZFOEEWI)
            Z1S = TANH(YDEPHLI%RLPAL2*(CUADJTQ_ZQSAT - CUADJTQ_ZQMAX))
            CUADJTQ_ZQSAT = 0.5_JPRB*((1.0_JPRB - Z1S)*CUADJTQ_ZQSAT + (1.0_JPRB + Z1S)*CUADJTQ_ZQMAX)
            
            CUADJTQ_ZCOR = 1.0_JPRB / (1.0_JPRB - YDCST%RETV*CUADJTQ_ZQSAT)
            CUADJTQ_ZQSAT = CUADJTQ_ZQSAT*CUADJTQ_ZCOR
            
